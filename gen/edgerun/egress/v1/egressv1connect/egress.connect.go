// Egress seam: outbound HTTP on behalf of guests, through a network service.
// Server: network service. Client: worker.
//
// A guest never touches the network itself. The worker has no route out for it:
// every outbound request a guest makes is handed to a network service over this
// protocol, and the service is the one place that decides whether it may leave,
// and does the leaving. That is what makes the policy enforceable (the worker
// need not be trusted with a network), observable, and replaceable (any
// implementation of this package will do).
//
// Closed by default: a call carries the destinations the calling function may
// reach (allow), and an empty list allows nothing. The service adds its own
// restrictions on top, which a caller cannot lift: it carries only what it
// declared (it registers with the orchestrator, see registry.proto) and it
// refuses the address classes the protocol docs name.

